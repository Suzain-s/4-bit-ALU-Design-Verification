def alu(a,b,operation):

    if operation=="ADD":
      return(a+b) & 0b1111

    elif operation=="SUB":
      return(a-b) & 0b1111

    elif operation=="AND":
      return(a&b)

    elif operation=="OR":
      return(a|b)

    elif operation=="XOR":
       return(a^b)

    else:
      raise ValueError("Invalid operation")

def verify_alu(a,b,operation,expected):

  actual = alu(a,b,operation)

